export type PixelGlyph = keyof typeof GLYPHS;

export function PixelIcon({ name, className }: { name: PixelGlyph; className?: string }) {
  const rows = GLYPHS[name];
  return (
    <svg viewBox="0 0 9 9" className={className ?? "size-4"} aria-hidden focusable="false" shapeRendering="crispEdges">
      {rows.flatMap((row, y) =>
        [...row].map((c, x) => (c === "#" ? <rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" fill="currentColor" /> : null)),
      )}
    </svg>
  );
}

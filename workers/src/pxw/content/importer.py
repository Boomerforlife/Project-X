"""Licence-gated import of validated rows as DRAFT questions. Never publishes anything.

Everything written for a batch happens in ONE transaction: committed at the end, rolled back on error or --dry-run.
Provenance (source_ref, licence, external_id, notes, file, row) has no column on `questions`, so it is written to an
append-only `audit_log` row per question (action 'content.import', actor_type 'WORKER').
"""

from __future__ import annotations

import uuid
from collections.abc import Sequence
from dataclasses import dataclass, field
from typing import Any

from psycopg.types.json import Jsonb

from pxw.common.errors import SourceNotApproved
from pxw.content.build import BuiltQuestion, build_question
from pxw.content.schema import RawRecord
from pxw.content.taxonomy import Taxonomy, load_db_taxonomy
from pxw.content.validate import PgLookup, ValidationReport, validate_records

_Q_COLUMNS = (
    "id", "exam_id", "subject_id", "chapter_id", "topic_id", "paper_id", "origin", "question_type", "difficulty",
    "year", "shift", "session_label", "question_number", "question_text", "structured_content", "answer_key",
    "answer_key_source", "source_id", "content_hash", "dedupe_text", "ingestion_status", "verification_status",
    "publication_status",
)
_Q_CASTS = {
    "origin": "question_origin", "question_type": "question_type", "difficulty": "difficulty",
    "answer_key_source": "answer_key_source", "ingestion_status": "ingestion_status",
    "verification_status": "verification_status", "publication_status": "publication_status",
}
_JSON_COLUMNS = {"structured_content", "answer_key"}


def question_insert_sql() -> str:
    cols = ", ".join(_Q_COLUMNS)
    vals = ", ".join(f"%s::{_Q_CASTS[c]}" if c in _Q_CASTS else "%s" for c in _Q_COLUMNS)
    # slug is generated by the questions_before_write trigger (as for promoted questions)
    return f"insert into questions ({cols}) values ({vals}) returning id, slug"


def question_params(q: dict[str, Any]) -> tuple[Any, ...]:
    return tuple(Jsonb(q[c]) if c in _JSON_COLUMNS and q[c] is not None else q[c] for c in _Q_COLUMNS)


OPTION_INSERT_SQL = (
    "insert into question_options (id, question_id, label, sort_order, content, content_text) values (%s, %s, %s, %s, %s, %s)"
)
SOLUTION_INSERT_SQL = (
    "insert into solution_versions (question_id, final_answer, steps, provenance, edit_note) "
    "values (%s, %s, %s, %s::solution_provenance, %s) returning id"
)
AUDIT_INSERT_SQL = (
    "insert into audit_log (actor_type, action, entity_type, entity_id, details) "
    "values ('WORKER', 'content.import', 'question', %s, %s)"
)


@dataclass
class ImportReport:
    dry_run: bool
    batch_id: str
    refused: str | None = None
    imported: list[dict[str, Any]] = field(default_factory=list)
    duplicates: list[dict[str, Any]] = field(default_factory=list)
    invalid: list[dict[str, Any]] = field(default_factory=list)
    solutions_created: int = 0
    validation: ValidationReport | None = None

    def to_dict(self) -> dict[str, Any]:
        return {
            "dry_run": self.dry_run,
            "batch_id": self.batch_id,
            "refused": self.refused,
            "imported": len(self.imported),
            "duplicates": len(self.duplicates),
            "invalid": len(self.invalid),
            "solutions_created": self.solutions_created,
            "committed": bool(self.imported) and not self.dry_run and not self.refused,
            "rows": {"imported": self.imported, "duplicates": self.duplicates, "invalid": self.invalid},
        }


def _insert(cur: Any, built: BuiltQuestion) -> tuple[str, str, bool]:
    cur.execute(question_insert_sql(), question_params(built.question))
    row = cur.fetchone()
    qid, slug = str(row["id"]), row["slug"]
    for o in built.options:
        cur.execute(
            OPTION_INSERT_SQL,
            (o["id"], o["question_id"], o["label"], o["sort_order"], Jsonb(o["content"]), o["content_text"]),
        )
    made_solution = False
    if built.solution:
        s = built.solution
        cur.execute(
            SOLUTION_INSERT_SQL,
            (s["question_id"], Jsonb(s["final_answer"]), Jsonb(s["steps"]), s["provenance"], s["edit_note"]),
        )
        made_solution = True
    cur.execute(AUDIT_INSERT_SQL, (qid, Jsonb(built.audit)))
    return qid, slug, made_solution


def import_rows(
    conn: Any,
    rows: Sequence[RawRecord],
    *,
    dry_run: bool,
    skip_invalid: bool = False,
    allow_examples: bool = False,
    taxonomy: Taxonomy | None = None,
    file_name: str | None = None,
) -> ImportReport:
    """Validate against the DB, then insert valid rows as DRAFT. One transaction; `dry_run` rolls it back.

    * Any source not licence-approved (unknown, reuse_permitted false, approved_at null) -> SourceNotApproved, nothing
      written (same condition as the source_documents trigger SOURCE_NOT_APPROVED).
    * Invalid rows refuse the whole batch unless `skip_invalid`; duplicates (content_hash already present, or repeated
      in the file) are always skipped and reported, which makes re-running a file idempotent.
    """
    report = ImportReport(dry_run=dry_run, batch_id=str(uuid.uuid4()))
    lookup = PgLookup(conn)
    try:
        codes = sorted({str(r.data["source"]).strip() for r in rows if r.data and r.data.get("source")})
        sources = lookup.get_sources(codes, lock=True)
        for code in codes:
            s = sources.get(code)
            if s is None:
                raise SourceNotApproved(f"SOURCE_NOT_APPROVED: unknown source {code!r}")
            if not s.is_approved:
                raise SourceNotApproved(f"SOURCE_NOT_APPROVED: source {code!r} is not reuse_permitted/approved")

        tax = taxonomy if taxonomy is not None and taxonomy.origin == "db" else load_db_taxonomy(conn)
        val = validate_records(rows, taxonomy=tax, db=lookup, allow_examples=allow_examples)
        report.validation = val
        for r in val.results:
            entry = r.to_dict()
            if r.status == "invalid":
                report.invalid.append(entry)
            elif r.status == "duplicate":
                report.duplicates.append(entry)
        if report.invalid and not skip_invalid:
            report.refused = f"{len(report.invalid)} invalid row(s); fix them or pass --skip-invalid"
            conn.rollback()
            return report

        with conn.cursor() as cur:
            for r in val.results:
                if r.status != "valid":
                    continue
                built = build_question(r, batch_id=report.batch_id, file_name=file_name)
                qid, slug, sol = _insert(cur, built)
                report.solutions_created += int(sol)
                report.imported.append({"row": r.index, "id": qid, "slug": slug, "content_hash": r.content_hash,
                                        "status": "DRAFT"})
        if dry_run or not report.imported:
            conn.rollback()
        else:
            conn.commit()
        return report
    except BaseException:
        conn.rollback()
        raise
